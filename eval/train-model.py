# Trains the small clause-type model in src/model-weights.ts. Developer-only: the app never runs Python.
#
#   node eval/dump-rule-hits.ts                 # which rules fire on each UNFAIR-ToS sentence
#   python eval/train-model.py                  # trains on train + validation, writes src/model-weights.ts
#   npm run eval -- test                        # the held-out score, from TypeScript
#
# Model: one logistic regression per clause type over word and word-pair TF-IDF features plus which
# rules fired. Vocabulary pruned to the 1,500 strongest words per type; thresholds picked by 5-fold
# cross-validation on train + validation. The test split is never used for any choice.
# Needs numpy, scipy and scikit-learn.
import json, os, sys
import numpy as np, scipy.sparse as sp
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import KFold

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "model-weights.ts")
C, TOPK, RW = 10.0, 1500, 1.0
TOK = r"(?u)\b\w+\b"
L = ["Limitation of liability", "Unilateral termination", "Unilateral change", "Content removal",
     "Contract by using", "Choice of law", "Jurisdiction", "Arbitration"]
RULE_IDS = ["collects_location", "collects_contacts", "collects_biometrics", "tracks_across_sites",
            "keeps_data_after_deletion", "sells_data", "shares_data", "broad_content_license", "ai_training",
            "content_removal", "arbitration", "class_action_waiver", "unilateral_change", "unilateral_termination",
            "contract_by_using", "limits_liability", "choice_of_law", "jurisdiction", "auto_renewal", "no_refunds",
            "arbitration_opt_out"]

def load(split):
    rows = json.load(open(os.path.join(HERE, "data", f"hits-{split}.json"), encoding="utf8"))
    X = [r["text"] for r in rows]
    Y = np.array([[int(l in r["labels"]) for l in L] for r in rows])
    R = np.array([[int(i in r["rules"]) for i in RULE_IDS] for r in rows])
    return X, Y, R

def f1(Y, P):
    tp = (Y & P).sum(); fp = ((1 - Y) & P).sum(); fn = (Y & (1 - P)).sum()
    return 2 * tp / (2 * tp + fp + fn)

(trX, trY, trR), (vaX, vaY, vaR) = load("train"), load("validation")
Xall = trX + vaX; Yall = np.vstack([trY, vaY]); Rall = np.vstack([trR, vaR])
def fit_vec(texts, vocab=None):
    return TfidfVectorizer(ngram_range=(1,2), sublinear_tf=True, min_df=1 if vocab else 2, token_pattern=TOK, vocabulary=vocab).fit(texts)
def mat(vec, texts, R): return sp.hstack([vec.transform(texts), sp.csr_matrix(R*RW)]).tocsr()
# 1. vocabulary selection from a full-vocab model
v0 = fit_vec(Xall); X0 = mat(v0, Xall, Rall); names = v0.get_feature_names_out(); nv = len(names)
keep = set()
for j in range(8):
    w = LogisticRegression(C=C, max_iter=4000).fit(X0, Yall[:,j]).coef_[0][:nv]
    keep.update(np.argsort(-np.abs(w))[:TOPK].tolist())
vocab = sorted(names[i] for i in keep)
print("vocab", nv, "->", len(vocab), flush=True)
# 2. thresholds from out-of-fold probabilities
P = np.zeros(Yall.shape)
for a, b in KFold(5, shuffle=True, random_state=0).split(Xall):
    ta = [Xall[i] for i in a]; tb = [Xall[i] for i in b]
    v = fit_vec(ta, vocab); Xa, Xb = mat(v, ta, Rall[a]), mat(v, tb, Rall[b])
    for j in range(8): P[b, j] = LogisticRegression(C=C, max_iter=4000).fit(Xa, Yall[a, j]).predict_proba(Xb)[:,1]
th = np.full(8, .5)
for _ in range(2):
    for j in range(8):
        best = (-1, .5)
        for t in np.arange(.06, .9, .02):
            t2 = th.copy(); t2[j] = t; s = f1(Yall, (P >= t2).astype(int))
            if s > best[0] + 1e-9: best = (s, t)
        th[j] = best[1]
print("CV micro-F1 %.3f" % f1(Yall, (P >= th).astype(int)), "thresholds", np.round(th, 2).tolist(), flush=True)
v = fit_vec(Xall, vocab); Xa = mat(v, Xall, Rall)
models = [LogisticRegression(C=C, max_iter=4000).fit(Xa, Yall[:, j]) for j in range(8)]
voc = v.vocabulary_; order = sorted(voc, key=voc.get); idx = [voc[t] for t in order]
out = {
    "labels": L, "ruleIds": RULE_IDS, "ruleWeight": RW,
    "vocab": order, "idf": [round(float(x), 4) for x in v.idf_[idx]],
    "bias": [round(float(m.intercept_[0]), 4) for m in models],
    "weights": [[round(float(x), 4) for x in m.coef_[0][:len(order)][idx]] for m in models],
    "ruleWeights": [[round(float(x), 4) for x in m.coef_[0][len(order):]] for m in models],
    "thresholds": [round(float(x), 2) for x in th],
}
with open(OUT, "w", encoding="utf8", newline="\n") as f:
    f.write("// Generated by eval/train-model.py from UNFAIR-ToS train + validation. Do not edit by hand.\n")
    f.write("// Word and word-pair TF-IDF + which rules fired -> logistic regression, one per clause type.\n")
    f.write("export const MODEL = " + json.dumps(out) + ";\n")
print("wrote", OUT, "- now run: npm run eval -- test")
